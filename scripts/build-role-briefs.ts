// `npm run briefs:build`: writes src/data/claims/role-briefs.ts from the 11
// role specs, the claims ledger, the skill tiers, the named gaps and his
// question bank (brief 3, task D1). It makes no model call. Run
// `npm run knowledge:build` first so src/generated/ledger.json is current.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { questionBank } from '../src/data/claims/question-bank.ts';
import { skillTierGroups } from '../src/data/claims/skill-tiers.ts';
import { namedGaps } from '../src/data/claims/wording-rules.ts';
import type { LedgerEntry } from '../src/lib/rag/ledger.ts';
import { buildRoleBrief, RoleBriefError } from './role-brief-rules.ts';
import { roleSpecs } from './role-requirements.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const claims = JSON.parse(
  await readFile(resolve(root, 'src/generated/ledger.json'), 'utf8'),
) as LedgerEntry[];

try {
  const briefs = roleSpecs.map((spec) =>
    buildRoleBrief(spec, {
      claims,
      tiers: skillTierGroups,
      namedGaps,
      bank: questionBank,
    }),
  );
  const file = `// Generated by \`npm run briefs:build\` from scripts/role-requirements.ts and
// the claims ledger. To change a brief, change the spec and run the command
// again; do not edit this file by hand. Each brief lists only direct and
// related evidence; what the site does not show is never listed.
import type { RoleBrief } from './types';

export const roleBriefs: readonly RoleBrief[] = ${JSON.stringify(briefs, null, 2)};
`;
  await writeFile(
    resolve(root, 'src/data/claims/role-briefs.ts'),
    file,
    'utf8',
  );
  for (const brief of briefs)
    process.stdout.write(
      `${brief.slug.padEnd(28)} direct ${brief.direct.length}, related ${brief.related.length}\n`,
    );
} catch (error) {
  if (!(error instanceof RoleBriefError)) throw error;
  process.stderr.write(`${error.message}\n`);
  process.exit(1);
}
